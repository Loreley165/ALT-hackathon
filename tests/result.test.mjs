import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { Window } from 'happy-dom';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const component = await build({ entryPoints: ['components/ALTNextShiftMission.jsx'], bundle: true, platform: 'node', format: 'esm', external: ['react'], write: false });
// Keep temporary transformed source beside its React dependency for resolution.
const { writeFile, unlink } = await import('node:fs/promises');
await writeFile('tests/.result-compiled.mjs', component.outputFiles[0].text);
const { default: Result, mockMission } = await import('./.result-compiled.mjs');
await unlink('tests/.result-compiled.mjs');

test('Stage 3 component renders missions and mock notice without Passport evidence', () => {
  const html = renderToStaticMarkup(React.createElement(Result));
  for (const item of mockMission.missions) assert.ok(html.includes(item.text));
  assert.ok(html.includes('Mock tasks'));
  assert.ok(!html.includes('alt-result__back'));
});
test('Reusable component accepts custom data, escapes text and has unique accessible ids', () => {
  const data = { ...mockMission, employee: '<script>unsafe</script>', missions: [] };
  const html = renderToStaticMarkup(React.createElement('div', null, React.createElement(Result, {data}), React.createElement(Result, {data})));
  assert.ok(html.includes('&lt;script&gt;'));
  const ids = [...html.matchAll(/id="([^"]+)"/g)].map(m => m[1]);
  assert.equal(ids.length, new Set(ids).size);
});
test('Try demo → transition → Alison Passport → Mission → back and navigation, no API calls', async () => {
  const window = new Window({ url: 'http://localhost:5173/', settings: { disableJavaScriptFileLoading: true, disableCSSFileLoading: true } });
  window.document.write(await readFile('index.html', 'utf8'));
  let requests = 0;
  window.fetch = () => { requests++; throw new Error('Unexpected network request'); };
  window.eval(await readFile('result-ui.js', 'utf8'));
  const nativeTimer = window.setTimeout.bind(window);
  const timers = [];
  window.setTimeout = (fn, ms, ...args) => [900,1800,2700].includes(ms) ? (timers.push({fn,ms}), timers.length) : nativeTimer(fn,ms,...args);
  window.setInterval = () => 0;
  window.eval(await readFile('app.js','utf8'));
  const $ = selector => window.document.querySelector(selector);
  $('#analyse').click();
  assert.equal($('#reflection-error').hidden, false);
  $('#try-demo').click();
  const reflection = $('#reflection').value;
  $('#analyse').click();
  assert.equal($('#analysis').hidden, false);
  assert.equal($('#result-screen').hidden, true);
  assert.deepEqual(timers.map(t=>t.ms), [900,1800,2700]);
  timers[0].fn(); assert.equal($('#evidence-step').hidden, false);
  timers[1].fn(); assert.equal($('#insights-step').hidden, false);
  timers[2].fn();
  await new Promise(resolve => setTimeout(resolve, 60));
  assert.equal($('#analysis').hidden, true);
  assert.equal($('#passport-placeholder').hidden, false);
  const passport = $('#passport-root').shadowRoot;
  assert.ok(passport.textContent.includes('Skill Passport'));
  assert.ok(passport.textContent.includes('Alex Chen'));
  assert.ok(passport.textContent.includes('Ready for Verification'));
  assert.ok(passport.textContent.includes(reflection));
  passport.querySelector('.passport-handoff button').click();
  await new Promise(resolve => setTimeout(resolve, 40));
  assert.equal($('#result-screen').hidden, false);
  assert.equal(window.document.querySelectorAll('.alt-result__evidence li').length, 0);
  assert.equal(window.document.querySelectorAll('.alt-result__missions li').length, 3);
  $('.alt-result__save').click();
  await new Promise(resolve => setTimeout(resolve, 30));
  assert.equal(JSON.parse(window.localStorage.getItem('alt-next-shift-mission-v1')).missions.length, 3);
  assert.equal($('.alt-result__save').disabled, true);
  assert.equal($('#saved-mission').hidden, false);
  $('.alt-result__back').click();
  assert.equal($('#result-screen').hidden,true);
  assert.equal($('#reflection-form').hidden,false);
  assert.equal($('#reflection').value,'');
  $('[data-nav="profile"]').click();
  assert.equal($('#profile-screen').hidden,false);
  assert.equal($('.reflection').hidden,true);
  assert.equal($('[data-nav="profile"]').getAttribute('aria-current'),'page');
  $('[data-nav="passport"]').click();
  assert.equal($('#profile-screen').hidden,true);
  assert.equal($('#passport-placeholder').hidden,false);
  assert.equal($('.reflection').hidden,true);
  assert.equal($('[data-nav="passport"]').getAttribute('aria-current'),'page');
  $('[data-nav="today"]').click();
  assert.equal($('#reflection-form').hidden,false);
  assert.equal($('#reflection').value,'');
  assert.equal(window.document.querySelectorAll('[data-nav][aria-current="page"]').length,1);
  assert.equal($('.app-shell').contains($('.bottom-nav')),false);
  $('#saved-mission').click();
  await new Promise(resolve => setTimeout(resolve, 30));
  assert.equal($('.alt-result__save').textContent, '✓ Saved for Next Shift');
  assert.equal(requests,0);
  await window.happyDOM.abort();
});
